/**
 * Renderers.
 *
 * A renderer is a pure `Bundle -> string | Buffer`. They are looked up by
 * {@link OutputFormat}, so `--format markdown,xml,zip` is just an iteration.
 *
 * The Markdown renderer is the reference implementation: it is the one most
 * chats consume, and the one every other renderer stays structurally parallel
 * to (front matter, summary, tree, analyzers, files, appendix).
 *
 * @module renderers
 */

import type {
  Bundle,
  FileRecord,
  OutputFormat,
  RenderContext,
  Renderer,
} from "../types.js";
import { fenceHint } from "../core/languages.js";
import { withLineNumbers } from "../core/compressor.js";
import { formatBytes, formatCount, formatDuration } from "../utils/style.js";
import { contextFit, estimateCost } from "../utils/tokenizer.js";
import { renderZip } from "./zip.js";

/** Front matter every text renderer shares. */
export interface FrontMatter {
  title: string;
  generatedAt: string;
  preset: string;
  compression: string;
  files: number;
  tokens: number;
  bytes: string;
}

/** Build the shared front matter for a bundle. */
export function frontMatter(bundle: Bundle): FrontMatter {
  return {
    title: `${bundle.scan.root.split(/[\\/]/).pop() ?? "project"} \u2014 AI context bundle`,
    generatedAt: bundle.startedAt,
    preset: bundle.config.preset,
    compression: bundle.config.compression,
    files: bundle.totals.included,
    tokens: bundle.totals.tokens,
    bytes: formatBytes(bundle.totals.includedBytes),
  };
}

/** Pick the files that actually go into the bundle body, in rank order. */
export function bundledFiles(bundle: Bundle): FileRecord[] {
  return bundle.scan.files.filter(
    (file) => !file.dropped && !file.binary && file.content !== undefined,
  );
}

/** Remove a trailing newline so fences stay tight. */
function tidy(body: string): string {
  return body.replace(/\n+$/, "");
}

/** A ```` ``` ```` fence with the right language hint. */
export function fence(body: string, languageId: string): string {
  return `\`\`\`${fenceHint(languageId)}\n${tidy(body)}\n\`\`\``;
}

/** Table of contents built from the sections that will be rendered. */
function tableOfContents(bundle: Bundle, withFiles: boolean): string {
  const lines: string[] = [];
  let index = 1;
  lines.push(`${index++}. [Project summary](#${anchor("project summary")})`);
  if (bundle.config.includeTree)
    lines.push(`${index++}. [Directory tree](#${anchor("directory tree")})`);
  for (const section of bundle.sections) {
    if (
      section.id === "summary" ||
      section.id === "tree" ||
      section.id === "index"
    )
      continue;
    lines.push(`${index++}. [${section.title}](#${anchor(section.title)})`);
  }
  if (withFiles) lines.push(`${index++}. [Files](#${anchor("files")})`);
  if (bundle.config.includeReport)
    lines.push(`${index++}. [Appendix](#${anchor("appendix")})`);
  return lines.join("\n");
}

/** GitHub-style heading anchor. */
export function anchor(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");
}

/* -------------------------------------------------------------------------- */
/* Markdown                                                                   */
/* -------------------------------------------------------------------------- */

function renderMarkdown(bundle: Bundle): string {
  const { config } = bundle;
  const out: string[] = [];
  const fm = frontMatter(bundle);
  const files = bundledFiles(bundle);

  out.push(`# ${fm.title}`);
  out.push("");
  out.push(
    `> Generated by \`aibundle\` on ${fm.generatedAt} \u00b7 preset \`${fm.preset}\` \u00b7 compression \`${fm.compression}\``,
  );
  out.push("");
  out.push("| Files | ~Tokens | Included size | Generated in |");
  out.push("| ---: | ---: | ---: | ---: |");
  out.push(
    `| ${fm.files} | ${formatCount(fm.tokens)} | ${fm.bytes} | ${formatDuration(bundle.durationMs)} |`,
  );
  out.push("");

  if (config.includeToc) {
    out.push("## Table of contents");
    out.push("");
    out.push(tableOfContents(bundle, files.length > 0));
    out.push("");
  }

  for (const section of bundle.sections) {
    out.push(`## ${section.title}`);
    out.push("");
    const body = section.render({ config, scan: bundle.scan });
    if (body.trim().length > 0) out.push(body.trim());
    out.push("");
  }

  if (files.length > 0) {
    out.push("## Files");
    out.push("");
    for (const file of files) {
      out.push(renderFileHeader(file));
      out.push("");
      out.push(fence(fileBody(file, config.lineNumbers), file.language));
      out.push("");
    }
  }

  if (config.includeReport) {
    out.push("## Appendix");
    out.push("");
    out.push(renderAppendix(bundle));
    out.push("");
  }

  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

/** `### path \u2014 lang, size, lines` heading used by all text renderers. */
function renderFileHeader(file: FileRecord): string {
  const bits: string[] = [];
  bits.push(`${file.languageName}`);
  bits.push(formatBytes(file.includedSize ?? file.size));
  bits.push(`${formatCount(file.lines)} lines`);
  if (file.tokens) bits.push(`~${formatCount(file.tokens)} tokens`);
  if (file.truncated) bits.push("truncated to fit budget");
  if (file.compressed) bits.push("compressed");
  if (file.redactions) bits.push(`${file.redactions} secret(s) redacted`);
  return `### \`${file.path}\`\n\n_${bits.join(" \u00b7 ")}_`;
}

/** Body with optional line numbers. */
function fileBody(file: FileRecord, lineNumbers: boolean): string {
  const content = file.content ?? "";
  return lineNumbers ? withLineNumbers(content) : content;
}

/** Appendix: how the bundle was built, and what was left out. */
function renderAppendix(bundle: Bundle): string {
  const { config, scan } = bundle;
  const out: string[] = [];

  out.push("### Build configuration");
  out.push("");
  out.push("```json");
  out.push(
    JSON.stringify(
      {
        preset: config.preset,
        compression: config.compression,
        formats: config.formats,
        maxFileSize: config.maxFileSize,
        maxTokens: config.maxTokens,
        includeHidden: config.includeHidden,
        lineNumbers: config.lineNumbers,
        redactSecrets: config.redactSecrets,
        stripComments: config.stripComments,
      },
      null,
      2,
    ),
  );
  out.push("```");
  out.push("");

  out.push("### Run statistics");
  out.push("");
  out.push(`- Files discovered: **${scan.totals.discovered}**`);
  out.push(`- Files included: **${bundle.totals.included}**`);
  out.push(`- Files dropped: **${bundle.totals.dropped}**`);
  out.push(
    `- Bytes before compression: **${formatBytes(bundle.totals.bytes)}**`,
  );
  out.push(
    `- Bytes after compression: **${formatBytes(bundle.totals.includedBytes)}**`,
  );
  out.push(
    `- Bytes saved by compression: **${formatBytes(bundle.totals.compressionSavedBytes)}**`,
  );
  out.push(`- Estimated tokens: **${formatCount(bundle.totals.tokens)}**`);
  out.push(`- Secrets redacted: **${bundle.totals.redactions}**`);
  out.push(
    `- Files truncated to fit the budget: **${bundle.totals.truncated}**`,
  );
  out.push("");

  const fit = contextFit(bundle.totals.tokens);
  out.push("### Context-window fit");
  out.push("");
  out.push("| Model window | Tokens | Fits | Fill |");
  out.push("| --- | ---: | :---: | ---: |");
  for (const entry of fit) {
    out.push(
      `| ${entry.model} | ${formatCount(entry.window)} | ${entry.fits ? "\u2714" : "\u2716"} | ${entry.fillPercent.toFixed(1)}% |`,
    );
  }
  out.push("");
  out.push(
    `Approximate input cost at \`gpt-4o\` rates: **$${estimateCost(bundle.totals.tokens, "gpt-4o").toFixed(4)}** (estimate only).`,
  );
  out.push("");

  const dropped = scan.files.filter((file) => file.dropped);
  const ignored = scan.ignored;
  if (dropped.length > 0 || ignored.length > 0) {
    out.push("### What was left out");
    out.push("");
    for (const file of dropped.slice(0, 60))
      out.push(`- \`${file.path}\` \u2014 ${file.dropReason ?? "excluded"}`);
    const ignoredNotDropped = ignored.filter(
      (entry) => !dropped.some((file) => file.path === entry.path),
    );
    for (const entry of ignoredNotDropped.slice(0, 60))
      out.push(`- \`${entry.path}\` \u2014 ${entry.reason}`);
    const total = dropped.length + ignoredNotDropped.length;
    if (total > 120) out.push(`- \u2026 and ${total - 120} more`);
    out.push("");
  }

  return out.join("\n").trimEnd();
}

