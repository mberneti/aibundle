const renderers: Renderer[] = [
  {
    id: "markdown",
    label: "Markdown",
    extension: ".md",
    mime: "text/markdown",
    render: renderMarkdown,
  },
  {
    id: "xml",
    label: "XML documents",
    extension: ".xml",
    mime: "application/xml",
    render: renderXml,
  },
  {
    id: "json",
    label: "JSON",
    extension: ".json",
    mime: "application/json",
    render: renderJson,
  },
  {
    id: "plain",
    label: "Plain text",
    extension: ".txt",
    mime: "text/plain",
    render: renderPlain,
  },
  {
    id: "repomix",
    label: "Repomix-compatible",
    extension: ".repomix.md",
    mime: "text/markdown",
    render: renderRepomix,
  },
  {
    id: "zip",
    label: "ZIP archive",
    extension: ".zip",
    mime: "application/zip",
    render: renderZipBundle,
  },
];

/** All registered renderers. */
export function listRenderers(): readonly Renderer[] {
  return renderers;
}

/** Look up a renderer, throwing on an unknown id. */
export function rendererFor(format: OutputFormat): Renderer {
  const renderer = renderers.find((entry) => entry.id === format);
  if (!renderer)
    throw new Error(`no renderer registered for format "${format}"`);
  return renderer;
}

/** Register an extra renderer (used by `plugins/`). */
export function registerRenderer(renderer: Renderer): void {
  const existing = renderers.findIndex((entry) => entry.id === renderer.id);
  if (existing >= 0) renderers[existing] = renderer;
  else renderers.push(renderer);
}

/** File name a renderer produces for a configured basename. */
export function outputFileName(format: OutputFormat, baseName: string): string {
  return `${baseName}${rendererFor(format).extension}`;
}

