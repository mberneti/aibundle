/* XML (Claude-style <documents>)                                             */
/* -------------------------------------------------------------------------- */

/**
 * Escape XML text content.
 *
 * CDATA is used for file bodies instead, but attributes and simple text nodes
 * still need escaping.
 */
export function escapeXml(value: string): string {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** Wrap a body in CDATA, splitting any stray `]]>` terminator. */
export function cdata(body: string): string {
  return `<![CDATA[\n${body.replace(/\]\]>/g, "]]]]><![CDATA[>")}\n]]>`;
}

function renderXml(bundle: Bundle): string {
  const { config } = bundle;
  const files = bundledFiles(bundle);
  const fm = frontMatter(bundle);
  const out: string[] = [];

  out.push('<?xml version="1.0" encoding="UTF-8"?>');
  out.push(
    `<context_bundle generated_at="${escapeXml(fm.generatedAt)}" preset="${escapeXml(fm.preset)}" compression="${escapeXml(fm.compression)}" files="${fm.files}" estimated_tokens="${fm.tokens}">`,
  );

  if (config.includeMeta) {
    out.push("  <metadata>");
    out.push(
      `    <project name="${escapeXml(fm.title)}" root="${escapeXml(bundle.scan.root)}" />`,
    );
    out.push(
      `    <totals files="${bundle.totals.included}" dropped="${bundle.totals.dropped}" bytes="${bundle.totals.includedBytes}" tokens="${bundle.totals.tokens}" />`,
    );
    if (bundle.scan.stack.length > 0) {
      out.push("    <stack>");
      for (const entry of bundle.scan.stack) {
        out.push(
          `      <technology id="${escapeXml(entry.id)}" label="${escapeXml(entry.label)}">${escapeXml(entry.evidence)}</technology>`,
        );
      }
      out.push("    </stack>");
    }
    out.push("  </metadata>");
  }

  out.push("  <sections>");
  for (const section of bundle.sections) {
    const body = section.render({ config, scan: bundle.scan });
    out.push(
      `    <section id="${escapeXml(section.id)}" title="${escapeXml(section.title)}">`,
    );
    out.push(cdata(tidy(body)));
    out.push("    </section>");
  }
  out.push("  </sections>");

  out.push(`  <documents count="${files.length}">`);
  for (const file of files) {
    const attrs = [
      `path="${escapeXml(file.path)}"`,
      `language="${escapeXml(file.language)}"`,
      `kind="${escapeXml(file.kind)}"`,
      `size="${file.includedSize ?? file.size}"`,
      `lines="${file.lines}"`,
      `tokens="${file.tokens ?? 0}"`,
      `importance="${file.importance}"`,
    ];
    if (file.truncated) attrs.push('truncated="true"');
    if (file.compressed) attrs.push('compressed="true"');
    if (file.redactions) attrs.push(`redactions="${file.redactions}"`);
    out.push(`    <document ${attrs.join(" ")}>`);
    out.push(cdata(tidy(fileBody(file, config.lineNumbers))));
    out.push("    </document>");
  }
  out.push("  </documents>");

  out.push("</context_bundle>");
  return out.join("\n") + "\n";
}

