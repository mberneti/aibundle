/* JSON                                                                       */
/* -------------------------------------------------------------------------- */

function renderJson(bundle: Bundle): string {
  const { config } = bundle;
  const files = bundledFiles(bundle);
  const fm = frontMatter(bundle);

  const payload = {
    schema: "aibundle/bundle@2",
    generatedAt: fm.generatedAt,
    generator: { name: "aibundle", version: "2.0.0" },
    project: {
      root: bundle.scan.root,
      name: fm.title,
      preset: config.preset,
      compression: config.compression,
      stack: bundle.scan.stack,
      languages: bundle.scan.languages,
    },
    totals: {
      discovered: bundle.scan.totals.discovered,
      included: bundle.totals.included,
      dropped: bundle.totals.dropped,
      bytes: bundle.totals.bytes,
      includedBytes: bundle.totals.includedBytes,
      tokens: bundle.totals.tokens,
      redactions: bundle.totals.redactions,
      truncated: bundle.totals.truncated,
      compressionSavedBytes: bundle.totals.compressionSavedBytes,
      durationMs: bundle.durationMs,
    },
    sections: bundle.sections.map((section) => ({
      id: section.id,
      title: section.title,
      content: section.render({ config, scan: bundle.scan }),
      data: section.value,
    })),
    files: files.map((file) => ({
      path: file.path,
      language: file.language,
      languageName: file.languageName,
      kind: file.kind,
      size: file.size,
      includedSize: file.includedSize ?? file.size,
      lines: file.lines,
      tokens: file.tokens ?? 0,
      importance: file.importance,
      reasons: file.reasons,
      redactions: file.redactions ?? 0,
      truncated: Boolean(file.truncated),
      compressed: Boolean(file.compressed),
      content: file.content ?? "",
    })),
    excluded: [
      ...bundle.scan.files
        .filter((file) => file.dropped)
        .map((file) => ({
          path: file.path,
          reason: file.dropReason ?? "excluded",
        })),
      ...bundle.scan.ignored.filter(
        (entry) =>
          !bundle.scan.files.some(
            (file) => file.dropped && file.path === entry.path,
          ),
      ),
    ],
  };

  return JSON.stringify(payload, null, 2) + "\n";
}

/* -------------------------------------------------------------------------- */
/* Plain                                                                      */
/* -------------------------------------------------------------------------- */

function renderPlain(bundle: Bundle): string {
  const { config } = bundle;
  const files = bundledFiles(bundle);
  const fm = frontMatter(bundle);
  const rule = "=".repeat(78);
  const thin = "-".repeat(78);
  const out: string[] = [];

  out.push(rule);
  out.push(fm.title.toUpperCase());
  out.push(rule);
  out.push(`Generated: ${fm.generatedAt}`);
  out.push(`Preset: ${fm.preset}   Compression: ${fm.compression}`);
  out.push(
    `Files: ${fm.files}   ~Tokens: ${formatCount(fm.tokens)}   Size: ${fm.bytes}`,
  );
  out.push("");

  for (const section of bundle.sections) {
    out.push(rule);
    out.push(section.title.toUpperCase());
    out.push(rule);
    out.push(tidy(section.render({ config, scan: bundle.scan })));
    out.push("");
  }

  if (files.length > 0) {
    out.push(rule);
    out.push("FILES");
    out.push(rule);
    for (const file of files) {
      out.push(thin);
      out.push(`FILE: ${file.path}`);
      out.push(
        `LANG: ${file.languageName}  SIZE: ${formatBytes(file.includedSize ?? file.size)}  LINES: ${file.lines}  SCORE: ${file.importance}`,
      );
      out.push(thin);
      out.push(tidy(fileBody(file, config.lineNumbers)));
      out.push("");
    }
  }

  if (config.includeReport) {
    out.push(rule);
    out.push("APPENDIX");
    out.push(rule);
    out.push(renderAppendix(bundle));
    out.push("");
  }

  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

