/**
 * The repomix layout: a header block, then one section per file, each fenced
 * with `## File: path`. Familiar to anyone who has used repomix, and easy for a
 * model to parse because the file boundary is a heading, not an attribute.
 */
function renderRepomix(bundle: Bundle): string {
  const { config } = bundle;
  const files = bundledFiles(bundle);
  const fm = frontMatter(bundle);
  const out: string[] = [];

  out.push(
    `This file is a merged representation of the entire codebase, combined into a single document.`,
  );
  out.push("");
  out.push("```");
  out.push("================================================================");
  out.push("File Summary");
  out.push("================================================================");
  out.push(`Project: ${fm.title}`);
  out.push(`Generated: ${fm.generatedAt}`);
  out.push(`Preset: ${fm.preset}   Compression: ${fm.compression}`);
  out.push("");
  out.push(`Files: ${fm.files}`);
  out.push(`~Tokens: ${formatCount(fm.tokens)}`);
  out.push("");
  if (bundle.scan.stack.length > 0) {
    out.push("Stack:");
    for (const entry of bundle.scan.stack)
      out.push(`  ${entry.label} (${entry.evidence})`);
    out.push("");
  }
  out.push("Files:");
  for (const file of files) {
    out.push(
      `  ${file.path} (${formatBytes(file.includedSize ?? file.size)}, ${file.lines} lines)`,
    );
  }
  out.push("================================================================");
  out.push("```");
  out.push("");

  for (const section of bundle.sections) {
    out.push(`# ${section.title}`);
    out.push("");
    out.push(tidy(section.render({ config, scan: bundle.scan })));
    out.push("");
  }

  if (files.length > 0) {
    out.push("# Files");
    out.push("");
    for (const file of files) {
      out.push(`## File: ${file.path}`);
      out.push("");
      out.push(fence(fileBody(file, config.lineNumbers), file.language));
      out.push("");
    }
  }

  if (config.includeReport) {
    out.push("# Appendix");
    out.push("");
    out.push(renderAppendix(bundle));
    out.push("");
  }

  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

/* -------------------------------------------------------------------------- */
/* ZIP                                                                        */
/* -------------------------------------------------------------------------- */

function renderZipBundle(bundle: Bundle): Buffer {
  const files = bundledFiles(bundle);
  const entries: Array<{ path: string; content: string | Buffer }> = [];

  entries.push({ path: "README.md", content: renderMarkdown(bundle) });
  entries.push({ path: "project-context.md", content: renderMarkdown(bundle) });
  entries.push({ path: "project-context.xml", content: renderXml(bundle) });
  entries.push({ path: "project-context.json", content: renderJson(bundle) });
  entries.push({ path: "STRUCTURE.txt", content: renderPlain(bundle) });

  const manifest = {
    schema: "aibundle/manifest@2",
    generatedAt: bundle.startedAt,
    root: bundle.scan.root,
    preset: bundle.config.preset,
    compression: bundle.config.compression,
    totals: bundle.totals,
    stack: bundle.scan.stack,
    files: files.map((file) => ({
      path: file.path,
      tokens: file.tokens ?? 0,
      bytes: file.includedSize ?? file.size,
    })),
  };
  entries.push({
    path: "manifest.json",
    content: JSON.stringify(manifest, null, 2),
  });

  for (const file of files) {
    entries.push({
      path: `files/${file.path}`,
      content: fileBody(file, false),
    });
  }

  return renderZip(entries, { mtime: new Date(bundle.startedAt) });
}

